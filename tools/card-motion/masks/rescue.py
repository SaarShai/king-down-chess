import sys, os; sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from mask_lib import *
rgb = painting('rescue'); h, s, v = hsv(rgb)
sleeve = polygon(rgb, [(.08,0),(.29,0),(.32,.15),(.46,.22),(.58,.24),(.60,.36),(.605,.50),(.58,.57),(.52,.62),(.44,.605),(.37,.575),(.31,.50),(.24,.38),(.20,.30),(.15,.17)])
hand = polygon(rgb, [(.27,.16),(.40,.145),(.53,.18),(.57,.24),(.46,.30),(.30,.32)])
arm = polygon(rgb, [(.43,.56),(.62,.54),(.78,.80),(.76,.825),(.52,.845),(.49,.78)])
figure = np.maximum(np.maximum(sleeve, hand), arm)
skin = (h < .2) & (s > .12)
open_water = polygon(rgb, [(0,.78),(.08,.74),(.15,.71),(.21,.68),(.27,.70),(.33,.72),(.41,.68),(.42,.60),(.70,.62),(.82,.67),(1,.72),(1,.79),(0,.79)])
dark = (s > .6) & (h > .5) & (h < .7) & (v < .85)
below = polygon(rgb, [(0,.78),(1,.78),(1,1),(0,1)])
water = np.maximum(open_water * dark, below) * (1 - soften(arm, 1, 1))
ice = sleeve * (1 - soften(skin, 1, 0)) * (h > .4)
save('rescue', np.clip(soften(water, 0, 2) * 2 - 1, 0, 1), soften(1 - figure, 0, 2), soften(ice, 0, 1.5))
