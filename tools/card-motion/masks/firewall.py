top = [(0,0),(.235,0),(.235,.10),(.30,.095),(.385,.115),(.395,.185),(.45,.235),(.545,.19),(.565,.33),(.60,.325),(.655,.34),(.665,.44),(.745,.45),(.765,.56),(.805,.60),(.865,.56),(.90,.475),(.945,.455),(.96,.58),(1,.625)]
