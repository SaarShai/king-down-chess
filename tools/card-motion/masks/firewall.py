hot = warm & (((v > .42) & (s > .4)) | (v > .82))
flame = shrink(grow(fire * hot, 2), 2) * fire
keep = soften(ivory, 2, 2)
r = soften(flame, 1, 2) * soften(fire, 0, 2) * (1 - keep)

# The reflection: only warm light on the wet tiles. The dark tiles and the cold moon glints stay still.
wet = floor * warm * (v > .5) * (s > .35)
g = soften(wet, 1, 2.5) * soften(floor, 0, 2) * (1 - soften(ivory, 2, 2))

