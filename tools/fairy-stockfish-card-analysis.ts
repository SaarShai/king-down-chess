/** Replay card games without search. Keep the block split fixed before inspection. */
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {Game} from '../src/game';
import {setRules,DEFAULT_RULES} from '../src/rules/rules';
import {fromFen,toFen} from '../src/rules/setup';
import {TAG_POWER,cardAt,heldCount} from '../src/rules/engine';
import {fullActions} from './fairy-stockfish-full';
const root=resolve(process.argv[2]);
const manifest=JSON.parse(readFileSync(root+'/split.json','utf8'));
const hash=(s:string)=>createHash('sha256').update(s).digest('hex');
const summaries:any[]=[],positions:any[]=[];
for(const split of ['development','held-out']){
 const text=readFileSync(root+'/'+split+'.jsonl','utf8');if(hash(text)!==manifest.files[split+'.jsonl'])throw Error('Split differs');
 const selected:any[]=[];
 for(const line of text.trim().split('\n')){
  const {cohort,game:r}=JSON.parse(line);setRules(r.rules);const game=new Game();game.load(fromFen(r.fen));const spent:any[]=[];let choices=0,unusedAtEnd:any[]=[];
  for(let i=0;i<r.tokens.length;i++){
   const actions=fullActions(game.pos),m=actions.get(r.tokens[i]);if(!m)throw Error('Illegal saved action');
   const fairy=(game.pos.turn===0)===r.fairyWhite,cardChoices=[...actions].filter(([,a])=>a.power);
   if(fairy&&cardChoices.length){
    choices++;
    // Fixed chronological sample, independent of score or selected action.
    if(choices===1||choices===5||choices===10)selected.push({cohort,id:r.id,block:r.block,index:i,rules:r.rules,startFen:r.fen,history:r.tokens.slice(0,i),fen:toFen(game.pos),played:r.tokens[i],legal:[...actions.keys()],cardChoices:cardChoices.map(([token,a])=>({token,card:TAG_POWER[a.power!],via:a.via??null})),nativeInfo:r.trace[i].info});
   }
   if(m.power)spent.push({index:i,engine:fairy?'fairy':'current',card:TAG_POWER[m.power],via:m.via??null,captures:m.captures.length,heldAfter:undefined});
   game.play(m);
  }
  if(toFen(game.pos)!==r.terminalFen||game.status!==r.status)throw Error('Terminal replay differs');
  for(const side of [0,1]as const){const used=game.pos.used?.[side]??0;unusedAtEnd.push({engine:(side===0)===r.fairyWhite?'fairy':'current',cards:Array.from({length:heldCount(side,game.pos.drawn?.[side]??0)},(_,k)=>k).filter(k=>!(used>>k&1)).map(k=>cardAt(side,k))});}
  // Do not inspect held-out summaries while selecting repairs.
  if(split==='development')summaries.push({cohort,id:r.id,block:r.block,nativeScore:r.fairyScore,status:r.status,actions:r.tokens.length,choices,spent,unusedAtEnd});
 }
 const target=root+'/'+split+'-positions.jsonl';if(existsSync(target))throw Error('Preserve existing test set');writeFileSync(target,selected.map(x=>JSON.stringify(x)+'\n').join(''));
 positions.push({split,positions:selected.length,sha256:hash(readFileSync(target,'utf8'))});
}
setRules(DEFAULT_RULES);writeFileSync(root+'/development-analysis.json',JSON.stringify({method:'Exact replay; no causal or best-move labels. Held-out positions are generated by fixed chronological indices, without inspecting their outcomes.',summaries,positions},null,2)+'\n');
console.log(JSON.stringify({games:summaries.length,positions}));
