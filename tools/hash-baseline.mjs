#!/usr/bin/env node
/**
 * Baseline hash manifest for the King Down takeover (docs/TAKEOVER-PLAN.md §1).
 *
 *   node tools/hash-baseline.mjs            write docs/takeover/baseline.json
 *   node tools/hash-baseline.mjs --check    re-hash and compare; exit 1 on any change
 *
 * Git stores the text source and docs; the bulk generated data (sim/out/*.jsonl, sim/nnue,
 * art-src, the v0.7 dist copy) is deliberately not versioned, so this manifest is the only
 * record that a stored output moved. It is a snapshot, not a backup: run --check before and
 * after any long job.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const ROOT = process.cwd();
const OUT = 'docs/takeover/baseline.json';
const CHECK = process.argv.includes('--check');

/** Versioned or preserved paths to hash. Directories are walked; missing ones are an error. */
const ROOTS = [
  '.gitignore', 'index.html', 'package.json', 'package-lock.json', 'tsconfig.json', 'vite.config.ts',
  'LESSONS.md', 'TASKS.md',
  'src', 'tools', 'public', 'sim/specs', 'sim/tune', 'sim/nnue', 'sim/out', 'art-src', 'docs',
];
/** The manifest cannot include itself, and VCS noise never belongs in it. */
const SKIP = /(^|\/)(\.git|node_modules|docs\/takeover)(\/|$)|\.DS_Store$/;

function* walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (SKIP.test(relative(ROOT, p))) continue;
    const st = statSync(p);
    if (st.isDirectory()) yield* walk(p);
    else if (st.isFile()) yield p;
  }
}

function entries() {
  const out = [];
  for (const root of ROOTS) {
    const abs = resolve(ROOT, root);
    if (!existsSync(abs)) throw new Error(`baseline: ${root} is missing`);
    const st = statSync(abs);
    const files = st.isDirectory() ? [...walk(abs)] : [abs];
    for (const f of files) {
      const buf = readFileSync(f);
      out.push({
        path: relative(ROOT, f),
        bytes: buf.length,
        sha256: createHash('sha256').update(buf).digest('hex'),
      });
    }
  }
  return out;
}

const now = entries();
if (CHECK) {
  const old = JSON.parse(readFileSync(OUT, 'utf8')).files;
  const before = new Map(old.map(e => [e.path, e]));
  const after = new Map(now.map(e => [e.path, e]));
  let bad = 0;
  for (const [p, e] of before) {
    const a = after.get(p);
    if (!a) { console.error(`missing:  ${p}`); bad++; }
    else if (a.sha256 !== e.sha256 || a.bytes !== e.bytes) { console.error(`changed:  ${p}`); bad++; }
  }
  for (const p of after.keys()) if (!before.has(p)) { console.error(`added:    ${p}`); bad++; }
  console.log(bad ? `baseline: ${bad} difference(s) from ${OUT}` : `baseline: ${now.length} files match ${OUT}`);
  process.exitCode = bad ? 1 : 0;
} else {
  mkdirSync('docs/takeover', { recursive: true });
  const bytes = now.reduce((a, e) => a + e.bytes, 0);
  writeFileSync(OUT, JSON.stringify({
    note: 'Takeover baseline manifest (docs/TAKEOVER-PLAN.md §1). Generated by tools/hash-baseline.mjs; verify with --check.',
    generated: new Date().toISOString(),
    files: now, count: now.length, bytes,
  }, null, 1) + '\n');
  console.log(`baseline: ${now.length} files, ${(bytes / 2 ** 20).toFixed(1)} MB -> ${OUT}`);
}
