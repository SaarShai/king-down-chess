/**
 * The still pictures of the pieces (public/ui/pieces/<kind>-<w|b>.webp) are the rest frames of the character runtime:
 * the frame each figure shows on the board when its animated art is ready. The board draws a still before the runtime
 * loads, with the same pivot and size, so the change to the animated art does not show. The Guide, the title and the
 * promotion picker show the same pictures.
 *
 *   node tools/build-piece-stills.mjs [package folder, default public/character-runtime]
 *
 * Each character of the package has one per army: the pieces and each king design (king-<design>-<w|b>.webp).
 * It writes the pictures (each rest frame cut to its painted pixels) and src/render/painted/piece-stills.mjs (where
 * each picture sits in its frame). Run it again after a change to a rest frame; piece-stills.test.mjs fails until then.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { restBankOf } from '../src/render/painted/character-runtime.mjs';

const ARMIES = { white: 'w', black: 'b' };
const QUALITY = 80;

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const pack = resolve(root, process.argv[2] ?? 'public/character-runtime');

async function main() {
  const manifest = JSON.parse(await readFile(resolve(pack, 'manifest.json'), 'utf8'));
  const prints = JSON.parse(await readFile(resolve(pack, 'footprints.json'), 'utf8').catch(() => 'null'));
  const stills = {}, kinds = [...new Set(manifest.banks.map(b => b.character))].sort();
  for (const kind of kinds) for (const [army, letter] of Object.entries(ARMIES)) {
    const bank = restBankOf(manifest.banks.filter(b => b.character === kind && b.army === army));
    if (!bank) throw Error(`No rest bank for ${kind} ${army}`);
    const frame = bank.frames[0];
    const { data, info } = await sharp(resolve(pack, frame.url)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
    for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) if (data[(y * info.width + x) * 4 + 3]) {
      x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
    }
    const size = [x1 - x0 + 1, y1 - y0 + 1];
    await sharp(data, { raw: info }).extract({ left: x0, top: y0, width: size[0], height: size[1] })
      .webp({ quality: QUALITY, alphaQuality: 100, effort: 6 }).toFile(resolve(root, `public/ui/pieces/${kind}-${letter}.webp`));
    const footprint = prints?.frames?.[frame.sourceSha256?.slice(0, prints.keyLength)] ?? null;
    (stills[kind] ??= {})[army] = {
      sourceSha256: frame.sourceSha256, pivot: [bank.pivot[0] - x0, bank.pivot[1] - y0], size,
      registrationHeightPx: bank.registrationHeightPx, boardScale: bank.boardScale ?? null, footprint,
    };
  }
  const out = `// Generated by tools/build-piece-stills.mjs: where each still picture (public/ui/pieces) sits in its rest frame,
// in bank px. Do not edit by hand; run the tool after a change to a rest frame.
export const PIECE_STILLS=${JSON.stringify(stills)};
`;
  await writeFile(resolve(root, 'src/render/painted/piece-stills.mjs'), out);
  console.log(`Wrote ${kinds.length * 2} still pictures and src/render/painted/piece-stills.mjs`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
